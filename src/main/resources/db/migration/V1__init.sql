CREATE TABLE player (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash  VARCHAR(64)  NOT NULL UNIQUE,
  name        VARCHAR(16)  NOT NULL,
  created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  last_seen   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE feedback_thread (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id      BIGINT       NOT NULL REFERENCES player (id),
  category       VARCHAR(16)  NOT NULL,
  title          VARCHAR(60)  NOT NULL,
  status         VARCHAR(16)  NOT NULL,
  context        VARCHAR(1000),
  player_unread  BOOLEAN      NOT NULL DEFAULT FALSE,
  admin_unread   BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_feedback_thread_player ON feedback_thread (player_id);
CREATE INDEX idx_feedback_thread_updated ON feedback_thread (updated_at);

CREATE TABLE feedback_message (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id   BIGINT        NOT NULL REFERENCES feedback_thread (id),
  sender      VARCHAR(8)    NOT NULL,
  body        VARCHAR(2000) NOT NULL,
  created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_feedback_message_thread ON feedback_message (thread_id);
