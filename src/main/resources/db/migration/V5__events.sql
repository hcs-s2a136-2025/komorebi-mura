-- v0.14：管理人が開くイベント（釣り大会・イースター・ハロウィン・クリスマス・独自イベント）
CREATE TABLE game_event (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(60)   NOT NULL,
  kind        VARCHAR(20)   NOT NULL,
  scoring     VARCHAR(20)   NOT NULL,
  rules       VARCHAR(1000),
  starts_at   TIMESTAMP WITH TIME ZONE NOT NULL,
  ends_at     TIMESTAMP WITH TIME ZONE NOT NULL,
  join_fee    INT           NOT NULL DEFAULT 0,
  min_level   INT           NOT NULL DEFAULT 0,
  rewards     VARCHAR(2000) NOT NULL,
  status      VARCHAR(12)   NOT NULL DEFAULT 'scheduled',
  created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 参加者ごとの記録（score は順位を決める数）
CREATE TABLE event_score (
  event_id    BIGINT        NOT NULL REFERENCES game_event (id) ON DELETE CASCADE,
  player_id   BIGINT        NOT NULL,
  name        VARCHAR(40)   NOT NULL,
  score       BIGINT        NOT NULL DEFAULT 0,
  detail      VARCHAR(4000) NOT NULL DEFAULT '',
  updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  PRIMARY KEY (event_id, player_id)
);

-- 渡したごほうび。(イベント, プレイヤー) で1行だけなので、同じごほうびを二度は渡さない
CREATE TABLE event_reward (
  event_id    BIGINT        NOT NULL REFERENCES game_event (id) ON DELETE CASCADE,
  player_id   BIGINT        NOT NULL,
  rank_no     INT           NOT NULL,
  reward      VARCHAR(2000) NOT NULL,
  created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  claimed_at  TIMESTAMP WITH TIME ZONE,
  PRIMARY KEY (event_id, player_id)
);
