-- 村ごとに分けるもの：共有の村（shared_world の id ＝ 村の番号）・麻雀の卓（mj_state の id ＝ 村の番号）・伝言板・イベント・家の中身（house_room の鍵に村の番号をつける）
CREATE TABLE village (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(16)   NOT NULL,
  code        VARCHAR(12)   NOT NULL UNIQUE,
  owner_id    BIGINT,
  created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
INSERT INTO village (id, name, code, owner_id, created_at) VALUES (1, 'こもれび村', 'MAIN', NULL, CURRENT_TIMESTAMP);
ALTER TABLE village ALTER COLUMN id RESTART WITH 2;

ALTER TABLE player ADD COLUMN village_id BIGINT NOT NULL DEFAULT 1;
CREATE INDEX idx_player_village ON player (village_id);

ALTER TABLE board_post ADD COLUMN village_id BIGINT NOT NULL DEFAULT 1;
CREATE INDEX idx_board_post_village ON board_post (village_id, created_at);

ALTER TABLE game_event ADD COLUMN village_id BIGINT NOT NULL DEFAULT 1;

